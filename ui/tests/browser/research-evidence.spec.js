import { test, expect } from '@playwright/test'

test('live research passages save and retry with citations; offline stays explicit', async ({ page, request }, testInfo) => {
  test.skip(!process.env.PROWL_LIVE_RESEARCH, 'Requires explicit local research service and mounted drive')
  await page.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }))
  await page.goto('/')
  await page.getByText('Research passage search', { exact: false }).click()
  await page.getByRole('button', { name: 'Search and save passages' }).click()
  await expect(page.getByRole('heading', { name: 'Retrieved research passages' })).toBeVisible()
  const url = await page.getByRole('link', { name: 'Download saved research search' }).getAttribute('href')
  const saved = await (await request.get(url)).json()
  expect(saved.passages).toHaveLength(5)
  expect(saved.passages[0].record.citation.pmid).toBe('35406426')
  expect(await (await request.post('/research-evidence/responses', { data: saved.request })).json()).toEqual(saved)
  expect((await request.post('/research-evidence/responses', { data: { ...saved.request, question_id: 'eus' } })).status()).toBe(409)
  expect((await request.post('/research-evidence/responses', { data: { ...saved.request, patient_id: 'private' } })).status()).toBe(400)
  expect((await request.post('/research-evidence/responses', { data: saved.request, headers: { Origin: 'https://unrelated.example' } })).status()).toBe(403)
  const article = page.getByRole('article', { name: 'Saved research search' })
  await article.locator('summary').first().click()
  await expect(article.locator('blockquote').first()).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('research-live.png'), fullPage: true })
  await page.getByLabel('Research question', { exact: true }).selectOption('eus')
  await page.getByRole('button', { name: 'Search and save passages' }).click()
  await expect(page.getByRole('heading', { name: 'Retrieved research passages' })).toBeVisible()
  await page.route('**/research-evidence/responses', route => route.fulfill({ status: 503, body: '{}' }))
  await page.getByRole('button', { name: 'Search and save passages' }).click()
  await expect(page.getByRole('alert')).toContainText('save could not be confirmed')
  await expect(page.getByRole('link', { name: 'Download saved research search' })).toHaveCount(0)
})
