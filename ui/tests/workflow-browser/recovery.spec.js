import { test, expect } from '@playwright/test'

test('actual HTTP workflow exposes failure, reuses retrieval and preserves both runs', async ({ page, request }, testInfo) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route('https://fonts.googleapis.com/**', r => r.fulfill({ contentType: 'text/css', body: '' }))
  await page.goto('/')
  await page.getByText('Research evidence workflow', { exact: false }).click()
  await page.getByRole('button', { name: 'Run evidence workflow' }).click()
  await expect(page.getByRole('list', { name: 'Evidence workflow stages' })).toContainText('Select evidence: In progress')
  await expect(page.getByRole('alert')).toContainText('Generation failed verification')
  await expect(page.getByRole('article', { name: 'Saved workflow answer' })).toHaveCount(0)
  const firstUrl = await page.getByRole('link', { name: 'Download workflow history' }).getAttribute('href')
  const first = await (await request.get(firstUrl)).json()
  expect(first.state).toBe('failed')
  await page.getByRole('button', { name: 'Retry failed stage' }).click()
  await expect(page.getByRole('article', { name: 'Saved workflow answer' })).toBeVisible()
  await expect(page.getByRole('list')).toContainText('Retrieve passages: Reused from prior attempt')
  const nextUrl = await page.getByRole('link', { name: 'Download workflow history' }).getAttribute('href')
  const next = await (await request.get(nextUrl)).json()
  expect(next.run_id).not.toBe(first.run_id)
  expect(next.request.resume_of).toBe(first.run_id)
  expect(next.events.filter(e => e.stage === 'retrieve').map(e => e.state)).toEqual(['reused'])
  expect(next.response.generation.provenance.fixture).toBe('synthetic-no-model')
  expect(await (await request.get(firstUrl)).json()).toEqual(first)
  expect(await (await request.post('/research-workflow/runs', { data: next.request })).json()).toEqual(next)
  const responseUrl = await page.getByRole('link', { name: 'Download workflow answer' }).getAttribute('href')
  expect(await (await request.get(responseUrl)).json()).toEqual(next.response)
  await page.setViewportSize({ width: 1280, height: 1050 })
  await page.getByText('Research evidence workflow', { exact: false }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('workflow-recovery.png'), fullPage: true })
  await page.getByLabel('Workflow question').selectOption('eus')
  await page.getByRole('button', { name: 'Run evidence workflow' }).click()
  await expect(page.getByRole('heading', { name: 'Insufficient evidence in the selected passages' })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Retry failed stage' })).toHaveCount(0)
  await page.reload()
  expect(await (await request.get(responseUrl)).json()).toEqual(next.response)
  expect(errors).toEqual([])
})
